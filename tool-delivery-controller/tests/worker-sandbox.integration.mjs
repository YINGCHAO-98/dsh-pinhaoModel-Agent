import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { WorkerWorkspaces } from '../workspace.mjs';
const config = { runtimePackageJson: '/Applications/DSH Desktop.app/Contents/Resources/app/package.json',
  sandbox: { backend: 'seatbelt', nodeExecutable: process.execPath } };

test('native tools edit and test isolated workspace, block host reads/writes/network and revoke access', async t => {
  const projectDir = await mkdtemp(resolve(tmpdir(), 'worker-project-'));
  const secretDir = await mkdtemp(resolve(tmpdir(), 'worker-secret-'));
  const secret = resolve(secretDir, 'private.txt');
  await writeFile(secret, 'host secret');
  const files = { 'src/a.cjs': Buffer.from('module.exports = 1;\n').toString('base64'), 'tests/a.cjs': Buffer.from('test').toString('base64') };
  const manager = new WorkerWorkspaces(config);
  const abort = new AbortController();
  const session = await manager.open(files, { session: { id: 'parent', header: { cwd: projectDir } } }, abort.signal);
  session.child = 'worker';
  t.after(async () => { await manager.close(session); await rm(secretDir, { recursive: true, force: true }); await rm(projectDir, { recursive: true, force: true }); });
  const exec = { agent: { session: { id: 'worker', header: { parentSession: 'parent' } } }, signal: abort.signal };
  const call = (name, args) => manager.invoke(name, args, exec);
  const read = await call('read', { file_path: 'src/a.cjs' });
  assert.match(JSON.stringify(read), /module.exports/);
  await call('edit', { file_path: 'src/a.cjs', old_string: '= 1', new_string: '= 2' });
  await call('write', { file_path: 'src/new.txt', content: 'new' });
  await call('write', { file_path: resolve(projectDir, 'src/from-project-absolute.txt'), content: 'mapped, not host-written' });
  await call('write', { file_path: '/workspace/src/from-virtual-root.txt', content: 'virtual root' });
  assert.equal(await readFile(resolve(session.root, 'src/from-project-absolute.txt'), 'utf8'), 'mapped, not host-written');
  assert.equal(await readFile(resolve(session.root, 'src/from-virtual-root.txt'), 'utf8'), 'virtual root');
  await assert.rejects(readFile(resolve(projectDir, 'src/from-project-absolute.txt')), /ENOENT/);
  const glob = await call('glob', { pattern: '**/*.cjs' });
  assert.ok(glob.paths.includes('src/a.cjs'), JSON.stringify(glob));
  const grep = await call('grep', { pattern: 'module.exports', path: 'src' });
  assert.equal(grep.matches.length, 1);
  const shell = await call('bash', { command: 'node -e "if(require(\'./src/a.cjs\')!==2) process.exit(1)"', description: 'Test edited module' });
  assert.equal(shell.exitCode, 0, JSON.stringify(shell));
  await assert.rejects(call('read', { file_path: secret }), /outside/);
  const denied = await call('bash', { command: `cat '${secret}'`, description: 'Probe host read boundary' });
  assert.notEqual(denied.exitCode, 0);
  const writeDenied = await call('bash', { command: `echo changed > '${secret}'`, description: 'Probe host write boundary' });
  assert.notEqual(writeDenied.exitCode, 0);
  assert.equal(await readFile(secret, 'utf8'), 'host secret');
  const net = await call('bash', { command: 'node -e "require(\'net\').connect(80,\'1.1.1.1\').on(\'error\',()=>process.exit(7))"', description: 'Probe network boundary', timeoutMs: 2000 });
  assert.notEqual(net.exitCode, 0);
  const timeout = await call('bash', { command: 'sleep 10', description: 'Probe timeout', timeoutMs: 100 });
  assert.equal(timeout.timedOut, true);
  await assert.rejects(call('bash', { command: 'true', description: 'No background', run_in_background: true }), /disabled/);
  process.env.PINHAOMO_TEST_SECRET = 'fixture-do-not-inherit';
  t.after(() => { delete process.env.PINHAOMO_TEST_SECRET; });
  const env = await call('bash', { command: `node -e "console.log(process.env.PINHAOMO_TEST_SECRET ?? 'absent')"`, description: 'Check clean environment' });
  assert.match(env.stdout.text, /absent/);
  await assert.rejects(call('bash', { command: 'true', description: 'Reject escaped cwd', workdir: secretDir }), /outside/);
  const scratchFile = resolve(session.scratch, 'check.cjs');
  await call('write', { file_path: '$TMPDIR/check.cjs', content: "console.log('scratch-ok')" });
  await call('write', { file_path: '/scratch/virtual-check.txt', content: 'virtual-scratch-ok' });
  assert.equal(await readFile(resolve(session.scratch, 'virtual-check.txt'), 'utf8'), 'virtual-scratch-ok');
  assert.match(JSON.stringify(await call('read', { file_path: scratchFile })), /scratch-ok/);
  const scratchCheck = await call('bash', { command: 'node "$TMPDIR/check.cjs"', description: 'Run scratch check' });
  assert.equal(scratchCheck.exitCode, 0);
  assert.match(scratchCheck.stdout.text, /scratch-ok/);
  await assert.rejects(call('write', { file_path: '${TMPDIR}/../escape.cjs', content: 'bad' }), /outside/);
  const { symlink } = await import('node:fs/promises');
  await symlink(secretDir, resolve(session.scratch, 'escape'));
  await assert.rejects(call('write', { file_path: resolve(session.scratch, 'escape/private.txt'), content: 'bad' }), /Symlink/);
  const proposal = await manager.proposal(session, files, 'done', { editablePaths: ['src/'], protectedPaths: ['tests/'], requiredPaths: ['tests/'] });
  assert.equal(proposal.changes.length, 4);
  await assert.rejects(call('read', { file_path: 'src/a.cjs' }), /WORKER_(NOT_BOUND|EXPIRED)/);
});

test('worker cancellation kills active command and expires its tools', async t => {
  const manager = new WorkerWorkspaces(config);
  const abort = new AbortController();
  const session = await manager.open({}, { session: { id: 'parent' } }, abort.signal);
  session.child = 'child';
  t.after(() => manager.close(session));
  const exec = { agent: { session: { id: 'child', header: { parentSession: 'parent' } } }, signal: abort.signal };
  const pending = manager.invoke('bash', { command: 'sleep 30', description: 'Cancellation probe' }, exec);
  setTimeout(() => abort.abort(), 150);
  await assert.rejects(pending);
  await assert.rejects(manager.invoke('read', { file_path: 'any' }, exec), /WORKER_(NOT_BOUND|EXPIRED)/);
});

test('quality workspace rejects file edits and shell writes but can run checks', async t => {
  const manager = new WorkerWorkspaces(config);
  const signal = new AbortController().signal;
  const session = await manager.open({ 'source.txt': Buffer.from('original').toString('base64') }, { session: { id: 'root' } }, signal);
  session.child = 'quality'; session.readOnly = true;
  t.after(() => manager.close(session));
  const exec = { agent: { session: { id: 'quality', header: { parentSession: 'root' } } }, signal };
  await assert.rejects(manager.invoke('write', { file_path: 'source.txt', content: 'changed' }, exec), /read-only/);
  const result = await manager.invoke('bash', { command: 'echo changed > source.txt', description: 'Must not change quality input' }, exec);
  assert.notEqual(result.exitCode, 0);
  assert.equal(await readFile(resolve(session.root, 'source.txt'), 'utf8'), 'original');
  const check = await manager.invoke('bash', { command: 'cat source.txt', description: 'Inspect quality input' }, exec);
  assert.equal(check.exitCode, 0);
});

test('root can write/read/edit its project while outside and symlink paths remain denied', async t => {
  const { symlink } = await import('node:fs/promises');
  const base = await mkdtemp(resolve(tmpdir(), 'root-files-'));
  const project = resolve(base, 'project');
  const { mkdir } = await import('node:fs/promises');
  await mkdir(project);
  const secret = resolve(base, 'outside.txt');
  await writeFile(secret, 'unchanged');
  const manager = new WorkerWorkspaces(config);
  const exec = { agent: { session: { id: 'root', header: { cwd: project } } }, signal: new AbortController().signal };
  const call = (name, args) => manager.invoke(name, args, exec);
  t.after(() => rm(base, { recursive: true, force: true }));
  await call('write', { file_path: 'page.html', content: '<html>first</html>' });
  await call('edit', { file_path: 'page.html', old_string: 'first', new_string: 'second' });
  assert.match(JSON.stringify(await call('read', { file_path: 'page.html' })), /second/);
  assert.equal(await readFile(resolve(project, 'page.html'), 'utf8'), '<html>second</html>');
  await assert.rejects(call('write', { file_path: secret, content: 'bad' }), /outside/);
  await assert.rejects(call('read', { file_path: '../outside.txt' }), /outside/);
  await symlink(secret, resolve(project, 'link'));
  await assert.rejects(call('write', { file_path: 'link', content: 'bad' }), /Symlink/);
  await assert.rejects(call('bash', { command: 'true' }), /ROOT_TOOL_NOT_ALLOWED/);
  assert.equal(await readFile(secret, 'utf8'), 'unchanged');
});

test('specialist can write/read its copy without changing project input', async t => {
  const manager = new WorkerWorkspaces(config);
  const signal = new AbortController().signal;
  const session = await manager.open({ 'source.txt': Buffer.from('original').toString('base64') }, { session: { id: 'root' } }, signal);
  manager.bind(session, 'specialist');
  session.allowedTools = ['read', 'write', 'edit'];
  const exec = { agent: { session: { id: 'specialist', header: { parentSession: 'root' } } }, signal };
  t.after(() => manager.close(session));
  await manager.invoke('write', { file_path: 'report.txt', content: 'report output' }, exec);
  assert.match(JSON.stringify(await manager.invoke('read', { file_path: 'report.txt' }, exec)), /report output/);
  await manager.invoke('edit', { file_path: 'source.txt', old_string: 'original', new_string: 'working copy' }, exec);
  assert.equal(await readFile(resolve(session.root, 'source.txt'), 'utf8'), 'working copy');
});
